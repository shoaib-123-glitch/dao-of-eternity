async def _create(pool, player, f):
    now = datetime.now(timezone.utc)
    repo = _repo(pool)
    say('Setup', player.label, '/start', await repo.start(GUILD, player.user, next(EVENTS), now))
    say('Setup', player.label, f'/awaken root:{ROOT}', await repo.awaken(GUILD, player.user, ROOT, BACKGROUND))
    await _console(pool, player, 'set_marks', marks=60)  # Pays for companion and sect founding.
    if player.companion:
        say('Setup', player.label, f'/adopt beast:{player.companion}', await _living_action(pool, player, 'adopt', player.companion))
    say('Setup', player.label, f'/sect_create name:{player.sect}', await _living_action(pool, player, 'sect_create', player.sect))
    if player.doctrine:
        say('Setup', player.label, f'/sect_doctrine doctrine:{player.doctrine}',
            await sect_halls.act(repo, GUILD, player.user, next(EVENTS), 'doctrine', player.doctrine))
    living = await _living(pool, player)
    f.expect(living.get('companion') == player.companion and living.get('sect') == player.sect, 'SETUP_' + player.label)


async def _world(env, f):
    if not getattr(env, 'story_ready', False):
        for player in (*PATHS, EXPLORER):
            await _create(env.pool, player, f)
        env.story_ready = True


