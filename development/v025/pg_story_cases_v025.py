# ---- case S4: exploration cooldown and daily caps --------------------------------------

async def exploration_caps(env):
    """S4. Five-minute cooldown, featured-region and rare-trail once per UTC day, cosmetic lore once per day."""
    f, pool = Findings(), env.pool
    await _activate(pool)
    await _world(env, f)
    d, section = EXPLORER, 'Exploration cooldown and daily caps'
    featured = living_world_v024.chapter(GUILD, datetime.now(timezone.utc))['region']
    other = next(region for region in living_dao.REGIONS if region not in (featured, 'mistwood'))
    item = living_dao.REGIONS[featured][2]
    before = (await _holdings(pool, d)).get(item, 0)
    reply = await _explore(pool, d, featured)
    say(section, d.label, f'/explore region:{featured} (featured today)', reply)
    f.expect('once per UTC day' in reply and (await _holdings(pool, d)).get(item, 0) - before == 2, 'FEATURED_BONUS_FIRST')
    message = await _refused(f, _explore(pool, d, featured, ready=False), 'spiritual senses are recovering', 'FIVE_MINUTE_COOLDOWN')
    say(section, d.label, f'/explore region:{featured} immediately again (refused)', message)
    before = (await _holdings(pool, d)).get(item, 0)
    reply = await _explore(pool, d, featured)
    say(section, d.label, 'Console: Exploration ready, then explore the featured region again', reply)
    f.expect('once per UTC day' not in reply and (await _holdings(pool, d)).get(item, 0) - before == 1, 'FEATURED_BONUS_CAPPED')
    say(section, d.label, 'Console: Featured and rare daily bonus ready', await _console(pool, d, 'world_daily_ready'))
    f.expect('once per UTC day' in await _explore(pool, d, featured), 'FEATURED_BONUS_AFTER_RESET')
    reply = await _explore(pool, d, other, RARE)
    say(section, d.label, f'/explore region:{other} (rare roll)', reply)
    f.expect('Rare trail encounter' in reply and 'Rare discovery' in reply, 'RARE_RESULTS_FIRST')
    lore = (await _story(pool, d)).get('lore_count')
    reply = await _explore(pool, d, other, RARE)
    say(section, d.label, f'/explore region:{other} (rare roll again, same day)', reply)
    f.expect('Rare trail encounter' not in reply and 'Rare discovery' not in reply, 'RARE_RESULTS_CAPPED')
    f.expect((await _story(pool, d)).get('lore_count') == lore, 'LORE_COUNTED_TWICE')
    await _console(pool, d, 'world_daily_ready')
    await _console(pool, d, 'story_lore_ready')
    reply = await _explore(pool, d, other, RARE)
    say(section, d.label, 'Console: both daily resets, then the rare roll again', reply)
    f.expect('Rare trail encounter' in reply and 'Rare discovery' in reply, 'RARE_RESULTS_AFTER_RESET')
    reply = await _explore(pool, d, 'mistwood')
    say(section, d.label, '/explore region:mistwood (story region, sect without doctrine)', reply)
    _reacted(f, reply, None, world.DOCTRINE_REACTIONS, 0, 'NO_DOCTRINE_SECT_LINE')
    f.expect('Jade Fox' not in reply, 'COMPANION_LINE_WITHOUT_COMPANION')
    f.finish()


# ---- case S5: overlapping play on one character ---------------------------------------

async def concurrent_play(env):
    """S5. Exploration, practice, a lesson and a console reset overlap on one character: nothing is lost."""
    f, pool = Findings(), env.pool
    await _activate(pool)
    await _world(env, f)
    a = PATHS[0]
    for key in ('exploration_ready', 'practice_ready', 'teacher_lesson_ready'):
        await _console(pool, a, key)
    marks, living, character = await _marks(pool, a), await _living(pool, a), await _character(pool, a)
    story = world._story(living)
    yue = story['npcs']['yue']['trust']
    mastery = character['cultivation_v023']['mastery'][ROOT]
    form = character.get('dao_practice_v025', {}).get('practices', 0)
    earned = living['beast_cultivation'].get('practice_earned', 0)
    explorations, actions = living['explorations'], character['dev_console_v025']['actions']
    gate = Gate(4)
    hooked = SimpleNamespace(pool=ObservedPool(pool, acquired=gate.arrive))
    with patch('secrets.randbelow', return_value=NO_RARE):
        results = await asyncio.wait_for(asyncio.gather(
            living_dao.action(storage.Repository(ObservedPool(pool, acquired=gate.arrive)), GUILD, a.user, next(EVENTS),
                              'explore', 'thunder_rift'),
            storage.Repository(ObservedPool(pool, acquired=gate.arrive)).execute(
                GUILD, a.user, next(EVENTS), 'cultivation_practice', datetime.now(timezone.utc)),
            world.train_story(storage.Repository(ObservedPool(pool, acquired=gate.arrive)), GUILD, a.user, next(EVENTS), 'yue'),
            console.run(hooked, GUILD, DEV, next(EVENTS), 'story_lore_ready', a.user, {}),
            return_exceptions=True), 30)
    for label, result in zip(('explore', 'practice', 'lesson', 'console'), results):
        f.expect(not isinstance(result, asyncpg.DeadlockDetectedError), 'DEADLOCK_40P01_' + label)
        f.expect(isinstance(result, str), f'CONCURRENT_{label.upper()}_FAILED_{type(result).__name__}')
        say('Concurrent play', a.label, f'Overlapping {label}', result if isinstance(result, str) else type(result).__name__)
    living, character = await _living(pool, a), await _character(pool, a)
    story = world._story(living)
    f.expect(await _marks(pool, a) == marks + living_dao.REGIONS['thunder_rift'][1], 'EXPLORE_MARKS_LOST')
    f.expect(living['explorations'] == explorations + 1, 'EXPLORATION_COUNT_LOST')
    f.expect(character['cultivation_v023']['mastery'][ROOT] == mastery + 4, 'PRACTICE_MASTERY_LOST')
    f.expect(character['dao_practice_v025']['practices'] == min(9, form + 1), 'FORM_PREPARATION_LOST')
    f.expect(living['beast_cultivation'].get('practice_earned', 0) == earned + 6, 'COMPANION_PRACTICE_QI_LOST')
    f.expect(story['npcs']['yue']['trust'] == min(12, yue + 1), 'LESSON_TRUST_LOST')
    f.expect(character['dev_console_v025']['actions'] == actions + 1, 'CONSOLE_UPDATE_LOST')
    f.finish()


