async def _character(pool, player):
    async with pool.acquire() as con:
        return json.loads(await con.fetchval('SELECT state::text FROM characters WHERE guild_id=$1 AND user_id=$2',
                                             GUILD, player.user))


async def _refused(f, job, fragment, label):
    """An expected game refusal: a ValueError whose text names the rule."""
    try:
        await job
    except ValueError as error:
        f.expect(fragment in str(error), label + '_WRONG_MESSAGE')
        return str(error)
    except Exception as error:  # A crash instead of a refusal is a finding, not a test stop.
        f.expect(False, f'{label}_RAISED_{type(error).__name__}')
        return type(error).__name__
    f.expect(False, label + '_NOT_REFUSED')
    return ''


async def _activate(pool):
    async with pool.acquire() as con:
        database = await con.fetchval('SELECT pg_catalog.current_database()::text')
        system_id = int(await con.fetchval('SELECT system_identifier FROM pg_catalog.pg_control_system()'))
    targets = frozenset(p.user for p in (*PATHS, EXPLORER))
    await console.activate(SimpleNamespace(pool=pool), console.ConsoleSettings(GUILD, database, system_id,
                                                                               frozenset({DEV}), targets))


async def _explore(pool, player, region, roll=NO_RARE, *, ready=True):
    if ready:
        await _console(pool, player, 'exploration_ready')
    with patch('secrets.randbelow', return_value=roll):
        return await _living_action(pool, player, 'explore', region)


def _trust_line(name, trust):
    label = 'Trusted ally' if trust >= 6 else 'Growing trust' if trust >= 3 else 'Acquaintance'
    return f'{name} · {label} {trust}/{world.MAX_TRUST}'


