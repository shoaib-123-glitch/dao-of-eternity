OBSERVED = {}  # companion or doctrine -> reaction lines actually shown


def _reacted(f, text, key, pools, chapter, label):
    """The reply shows a line from this chapter's pool; record it to check variety later."""
    hit = next((line for line in pools[key][chapter] if line in text), None)
    f.expect(hit is not None, label)
    if hit:
        OBSERVED.setdefault(key, set()).add(hit)
GOAL_SEEKER = Player(user=2005, label='Goal seeker E (fresh character)', option=None,
                     companion=None, doctrine=None, sect='Morning Dew')
LASTING = {'restore_beacon': 'A guardian lantern now guides the road.',
           'open_archive': 'Travelers exchange copies of the recovered records.',
           'reconcile': 'A shared training ground welcomes rival schools.'}
FORM_TEXT = {'guard': lambda rank: f'ward {2 * rank} against the next enemy hit',
             'flow': lambda rank: f'+{rank} Combat Qi', 'strike': lambda rank: f'+{rank} damage'}


class Findings:
    def __init__(self):
        self.failed = []

    def expect(self, condition, label):
        if not condition:
            self.failed.append(label)
        return bool(condition)

    def finish(self):
        if self.failed:
            raise AssertionError('; '.join(self.failed))


def say(section, path, action, text):
    TRANSCRIPT.append((section, path, action, str(text)))


def write_transcript(path):
    sections = OrderedDict()
    for section, who, action, text in TRANSCRIPT:
        sections.setdefault(section, OrderedDict()).setdefault(who, []).append((action, text))
    lines = ['# v0.25 Story Transcript — Echoes of the Fallen Heaven', '',
             'Generated by `run_pg_cases_v025.py` from the real game handlers against a throwaway database.',
             'Every player-facing reply is shown in order. Developer Console replies are marked; they stand in for',
             'waiting out cooldowns. Numbers such as Spirit Stones balances come from the run and are not hand-written.', '']
    for section, paths in sections.items():
        lines += [f'## {section}', '']
        for who, entries in paths.items():
            lines += [f'### {who}', '']
            for action, text in entries:
                lines.append(f'**{action}**')
                lines.append('')
                lines += ['> ' + line if line else '>' for line in text.splitlines()] or ['>']
                lines.append('')
    with open(path, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('\n'.join(lines))


