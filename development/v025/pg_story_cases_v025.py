async def teachers_and_duel(env):
    """S3. One lesson per UTC day across all teachers; Zhao's duel win, loss and invalid paths."""
    f, pool = Findings(), env.pool
    await _activate(pool)
    await _world(env, f)
    a, b, c = PATHS
    section = 'Teachers and the Zhao duel'
    now = datetime.now(timezone.utc)
    message = await _refused(f, _lesson(pool, EXPLORER, 'jian'), 'Complete the Stonepeak archive chapter', 'LESSON_BEFORE_UNLOCK')
    say(section, EXPLORER.label, 'Jian lesson before Stonepeak (refused)', message)
    order = world.duel_order(now)
    text = training_text(await _living(pool, a), now)
    f.expect(all(world.TELLS[stance] in text for stance in order) and 'answer with' not in text, 'DUEL_TELLS_ON_PANEL')
    say(section, a.label, 'Story panel · Teachers field', text)
    before = (await _story(pool, a))['npcs']['jian']['trust']
    reply = await _lesson(pool, a, 'jian')
    say(section, a.label, 'Jian Wuchen · Sword lesson', reply)
    story = await _story(pool, a)
    f.expect('Jian remembers the returned seal' in reply, 'JIAN_REMEMBERS_RETURNED_SEAL')
    f.expect(story['npcs']['jian']['trust'] == min(12, before + 1) and story['technique'] == 'Patient Edge', 'JIAN_LESSON_EFFECT')
    saved = await _living(pool, a)
    message = await _refused(f, _lesson(pool, a, 'yue'), 'next UTC day', 'SECOND_LESSON_SAME_DAY')
    say(section, a.label, 'Yue lesson on the same UTC day (refused)', message)
    f.expect(await _living(pool, a) == saved, 'REFUSED_LESSON_CHANGED_STATE')
    text = training_text(await _living(pool, a), now)
    f.expect('Next free lesson' in text, 'TEACHERS_FIELD_SHOWS_NEXT_DAY')
    say(section, a.label, 'Story panel · Teachers field after the lesson', text)
    say(section, a.label, 'Console: Teacher lesson ready', await _console(pool, a, 'teacher_lesson_ready'))
    reply = await _lesson(pool, a, 'yue')
    say(section, a.label, 'Yue Lian · Archive investigation', reply)
    f.expect((await _story(pool, a))['technique'] == 'Seeking Thread', 'YUE_RETUNES_FORM')
    await _console(pool, b, 'teacher_lesson_ready')
    reply = await _lesson(pool, b, 'yue')
    say(section, b.label, 'Yue Lian · Archive investigation', reply)
    f.expect('Yue recognizes the tracing' in reply, 'YUE_REMEMBERS_TRACING')
    marks = await _marks(pool, c)
    qi = (await _character(pool, c))['player']['qi']
    right = [world.COUNTERS[stance] for stance in order]
    wrong = [next(move for move in world.COUNTERS.values() if move != counter) for counter in right]
    for tactics, wins, gain in ((right, 3, 2), (wrong, 0, 1), (right[:2] + wrong[2:], 2, 2)):
        await _console(pool, c, 'teacher_lesson_ready')
        before = (await _story(pool, c))['npcs']['zhao']['trust']
        reply = await _lesson(pool, c, 'zhao', tactics)
        say(section, c.label, 'Zhao duel: ' + ' → '.join(t.title() for t in tactics), reply)
        story = await _story(pool, c)
        f.expect(f'{wins}/3 clean counters' in reply, f'DUEL_{wins}_OF_3_TEXT')
        f.expect(all(f'{n}. Zhao {stance.title()}' in reply for n, stance in enumerate(order, 1)), 'DUEL_ORDER_NOT_TODAYS')
        f.expect(story['npcs']['zhao']['trust'] == min(12, before + gain) and story['technique'] == 'Shared Horizon',
                 f'DUEL_{wins}_OF_3_TRUST')
    f.expect(await _marks(pool, c) == marks and (await _character(pool, c))['player']['qi'] == qi, 'DUEL_CHANGED_MARKS_OR_QI')
    await _console(pool, c, 'teacher_lesson_ready')
    saved = await _story(pool, c)
    message = await _refused(f, _lesson(pool, c, 'zhao', ['guard', None, 'feint']), 'Zhao needs three tactics', 'DUEL_MISSING_TACTIC')
    say(section, c.label, 'Zhao duel with exchange 2 unchosen (refused)', message)
    f.expect(await _story(pool, c) == saved, 'INVALID_DUEL_SPENT_THE_LESSON')
    # Trust thresholds and the cap of 12, set directly, then read back from the story panel.
    for trust, label in ((2, 'Acquaintance'), (3, 'Growing trust'), (5, 'Growing trust'), (6, 'Trusted ally'), (12, 'Trusted ally')):
        await _console(pool, a, 'story_set_trust', npc='jian', trust=trust)
        f.expect(f'Jian Wuchen · {label} {trust}/12' in world.status(await _living(pool, a)), f'TRUST_LABEL_{trust}')
    for _ in range(4):  # Trust stays capped; memories never exceed six.
        await _console(pool, a, 'teacher_lesson_ready')
        reply = await _lesson(pool, a, 'jian')
    say(section, a.label, 'Jian lesson at trust 12', reply)
    jian = (await _story(pool, a))['npcs']['jian']
